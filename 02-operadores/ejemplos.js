// Operadores matemáticos

const num1 = 10;
const num2 = 5;

console.log(`Suma: ${num1 + num2}`);
console.log(`Resta: ${num1 - num2}`);
console.log(`Multiplicación: ${num1 * num2}`);
console.log(`División: ${num1 / num2}`);
console.log(`Resto: ${num1 % num2}`);

let puntos = 10;

puntos += 5;
console.log(`Puntos: ${puntos}`);

puntos -= 3;
console.log(`Puntos: ${puntos}`);

puntos *= 2;
console.log(`Puntos: ${puntos}`);

puntos /= 4;
console.log(`Puntos: ${puntos}`);
